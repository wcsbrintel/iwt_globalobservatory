# Indicators must be unambiguous and in the original recorded narrative.
# The published classification is a thematic navigation aid, not a criminal judgement.
PATTERNS={
 "mining":r"\b(?:GARIMP\w*|MINERA(?:C|Ç)\w*|EXTRACAO MINERAL|EXTRA(?:C|Ç)AO DE MINERIO|LAVRA MINERAL|DRAGA DE GARIMPO|EXTRACAO DE OURO|OURO ALUVIONAR)\b",
 "logging":r"\b(?:MADEIRA(?:S)?|TORAS?|SERRARI\w*|LENHA|CARV[ÃA]O VEGETAL|PRODUT\w* FLOREST\w*|EXPLORA(?:C|Ç)AO FLORESTAL|TRANSPORTE FLORESTAL)\b",
 "deforestation":r"\b(?:DESMAT\w*|SUPRIM\w* VEGETA\w*|SUPRESSAO DE VEGETACAO|CORTE RASO|DESTRUI\w* FLORESTA|DESTRUI\w* VEGETA\w*|DESFLOREST\w*)\b",
 "fire":r"\b(?:QUEIMAD\w*|INCENDI\w*|FOGO IRREGULAR|USO DE FOGO)\b",
 "pollution":r"\b(?:POLUI\w*|CONTAMINA\w*|EFLUENT\w*|MERCURIO|REJEITOS? TOXICOS?|DERRAMAMENT\w*)\b",
 "fishing":r"\b(?:PESC\w*|PIRACEMA|PESCADO|RECURS\w* PESQUEIR\w*)\b",
 "wildlife":r"\b(?:ANIMA(?:L|IS) SILVESTR\w*|FAUNA|CACA PREDATORIA|CACAR ANIMAIS|COMERCIO DE ANIMAIS)\b",
}
# Do not expose raw narrative: it can contain personal names, contact information and addresses.
def normalize(text):
 import unicodedata
 text=unicodedata.normalize("NFKD",str(text or ""))
 return "".join(c for c in text if not unicodedata.combining(c)).upper()
def get(row,*cols):
 return next((str(row[x]).strip() for x in cols if x in row and row[x] is not None and str(row[x]).strip()),"")
def safe(s,n=140):
 return re.sub(r"[\x00-\x1f]+"," ",str(s or "")).strip()[:n]
def public_narrative(value, limit=12000):
 # The official source is public, but embedded identifiers must not be
 # indiscriminately redistributed in searchable map popups.
 text = re.sub(r"[\x00-\x1f]+", " ", str(value or "")).strip()
 text = re.sub(r"(?i)\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b", "[e-mail omitido]", text)
 text = re.sub(r"(?i)\b(?:CPF|CNPJ|RG)\s*(?:N[º°.]?\s*)?[:#=-]?\s*[0-9.\-/]{7,22}", "[identificador pessoal omitido]", text)
 text = re.sub(r"(?i)\b(?:PLACAS?)(?:\s+(?:DO|DA|DE|N[º°.]?))?\s*[:#=-]?\s*[A-Z]{3}[-\s]?[0-9][A-Z0-9][0-9]{2}\b", "placa [omitida]", text)
 text = re.sub(r"(?i)\b(?:RENAVAM|CHASSIS?|CHASSI)\s*(?:N[º°.]?\s*)?[:#=-]?\s*[A-Z0-9-]{7,24}\b", "[identificador de veículo omitido]", text)
 text = re.sub(r"(?i)\b(?:TELEFONE|CELULAR|WHATSAPP)\s*[:#=-]?\s*\+?[0-9() .-]{9,25}", "[contato omitido]", text)
 return re.sub(r"\s+", " ", text).strip()[:limit]

def number(s):
 if not s:return None
 try:
  s=str(s).strip().replace(" ","")
  if "," in s and "." in s:s=s.replace(".","").replace(",",".")
  elif "," in s:s=s.replace(",",".")
  x=float(s)
  if not (-1e15<x<1e15):return None
  return x
 except ValueError:return None
def item_add(target, item):
 target.append(item)

def download(url, name):
 req=urllib.request.Request(url,headers={"User-Agent":"WCSBrasil-IBAMA-2020-2025-official-enrichment"})
 path=None
 try:
  with tempfile.NamedTemporaryFile(suffix=".bin",delete=False) as f:
   path=f.name; size=0
   with urllib.request.urlopen(req,timeout=150) as resp:
    while True:
     b=resp.read(1048576)
     if not b:break
     size+=len(b)
     if size>MAX_DOWNLOAD:raise RuntimeError(name+" exceeds download size limit")
     f.write(b)
  return path
 except Exception:
  if path and os.path.exists(path):os.unlink(path)
  raise

def rows(path,annual=False):
 if zipfile.is_zipfile(path):
  with zipfile.ZipFile(path) as z:
   members=[n for n in z.namelist() if n.lower().endswith(".csv")]
   if annual:
    members=[n for n in members if re.search(r"202[0-5][^/]*\.csv$",n,re.I)]
   if not members:raise RuntimeError("No 2020-2025 CSV in official ZIP" if annual else "No CSV in official ZIP")
   for name in members:
    with z.open(name) as raw:
     sample=raw.read(6000)
    try: sample.decode("utf-8-sig"); encoding="utf-8-sig"
    except UnicodeDecodeError:encoding="latin-1"
    with z.open(name) as raw:
     text=io.TextIOWrapper(raw,encoding=encoding,errors="replace",newline="")
     first=text.readline()
     delimiter=";" if first.count(";")>=first.count(",") else ","
     reader=csv.DictReader(itertools.chain([first],text),delimiter=delimiter)
     print("AUDIT RESOURCE HEADER",name,json.dumps(reader.fieldnames,ensure_ascii=False),flush=True)
     for row in reader:yield {str(k).strip().upper():v for k,v in row.items() if k}
 else:
  with open(path,"rb") as raw:
   text=io.TextIOWrapper(raw,encoding="utf-8-sig",errors="replace",newline="")
   first=text.readline()
   delimiter=";" if first.count(";")>=first.count(",") else ","
   reader=csv.DictReader(itertools.chain([first],text),delimiter=delimiter)
   print("AUDIT RESOURCE HEADER CSV",json.dumps(reader.fieldnames,ensure_ascii=False),flush=True)
   for row in reader:yield {str(k).strip().upper():v for k,v in row.items() if k}

def categorize(row, original):
 tipo=normalize(get(row,"TIPO_INFRACAO"))
 descriptor=" ".join(normalize(get(row,k)) for k in
    ("DES_INFRACAO","DES_AUTO_INFRACAO","DS_ENQUADRAMENTO_ADMINISTRATIVO",
     "DS_ENQUADRAMENTO_NAO_ADMINISTRATIVO","OPERACAO","FUNDAMENTACAO_MULTA"))
 categories=set()
 for key,regex in PATTERNS.items():
  if re.search(regex,descriptor):categories.add(key)
 if "FAUNA" in tipo:categories.add("wildlife")
 if tipo=="PESCA":categories.add("fishing")
 if tipo=="FLORA" and not (categories & {"deforestation","logging","fire"}):categories.add("flora_other")
 if not categories:categories.add("other")
 # Avoid presenting "other" and a specific classification together.
 if len(categories)>1:categories.discard("other")
 primary=original if original in categories else next(iter(sorted(categories)))
 return sorted(categories),primary

def main():
 datasets={}
 features=[]
 byseq={}
 by_notice=collections.defaultdict(list)
 for year in YEARS:
  path=os.path.join(DATA_DIR,"ibama-"+str(year)+".json")
  with open(path,encoding="utf-8") as source:
   data=json.load(source)
  if data.get("year")!=year or not data.get("features"):
   raise RuntimeError("Invalid original IBAMA dataset for "+str(year))
  datasets[year]=data
  features.extend(data["features"])
  for feature in data["features"]:
   ident=feature["properties"].get("id","")
   prefix="IBAMA-"+str(year)+"-"
   if ident.startswith(prefix):
    key=ident[len(prefix):]
    if key in byseq:
     raise RuntimeError("Official sequence ID reused across years: "+key)
    byseq[key]=feature
   notice=feature["properties"].get("notice","").strip().upper()
   if notice:by_notice[notice].append(feature)
 counters=collections.Counter();status={}
 terms_by_seq=collections.defaultdict(list)
 loaded={}
 
 # 1. Original annual autos with explicit official occurrence date, administrative
 # legal classification, affected area, operations and matching references.
 path=download(URLS["autos"],"autos")
 try:
  for row in rows(path,annual=True):
   key=get(row,"SEQ_AUTO_INFRACAO")
   if not key:
    key=re.sub("[^A-Za-z0-9_-]","",get(row,"NUM_AUTO_INFRACAO")+"-"+get(row,"SER_AUTO_INFRACAO"))[:45]
   f=byseq.get(key)
   if not f:continue
   p=f["properties"]
   cats,primary=categorize(row,p["category"])
   p["categories"]=cats;p["category"]=primary
   area=number(get(row,"QT_AREA"))
   p["official"]={
     "infraction_code":safe(get(row,"COD_INFRACAO"),25),
     "administrative_class":safe(get(row,"TIPO_INFRACAO"),90),
     "infraction_description":safe(get(row,"DES_INFRACAO"),240),
     "narrative_detail":public_narrative(get(row,"DES_AUTO_INFRACAO"),12000),
     "administrative_legal_basis":safe(get(row,"DS_ENQUADRAMENTO_ADMINISTRATIVO"),500),
     "non_administrative_legal_basis":safe(get(row,"DS_ENQUADRAMENTO_NAO_ADMINISTRATIVO"),400),
     "additional_legal_basis":safe(get(row,"DS_ENQUADRAMENTO_COMPLEMENTAR"),300),
     "affected_area":area,
     "affected_area_unit":"", # Unit not asserted without verified field dictionary
     "area_classification":safe(get(row,"CLASSIFICACAO_AREA"),120),
     "biomes":safe(get(row,"DS_BIOMAS_ATINGIDOS"),180),
     "protected_area":safe(get(row,"UNIDADE_CONSERVACAO"),160),
     "operation":safe(get(row,"OPERACAO"),100),
     "process":safe(get(row,"NU_PROCESSO_FORMATADO"),40),
     "fine_brl":number(get(row,"VAL_AUTO_INFRACAO")),
     "fact_date":safe(get(row,"DT_FATO_INFRACIONAL"),30),
     "inspection_action":safe(get(row,"CD_ACAO_FISCALIZATORIA"),30),
     "reference":CATALOG,
     "seizure_term_references":safe(get(row,"CD_TERMOS_APREENSAO"),2000),
     "administrative_status":safe(get(row,"DS_SIT_AUTO_AIE","DES_STATUS_FORMULARIO"),120)
   }
   counters["autos_enriched"]+=1
  loaded["autos"]="ok"
 finally:os.unlink(path)
 
 # 2. Official species table linked directly by SEQ_AUTO_INFRACAO.
 # These are species mentioned in the notice; NOT automatically "seized".
 try:
  path=download(URLS["species_in_auto"],"auto species")
  for row in rows(path):
   f=byseq.get(get(row,"SEQ_AUTO_INFRACAO"))
   if not f:continue
   p=f["properties"]; entries=p.setdefault("species_referenced",[])
   item={"scientific_name":safe(get(row,"NOME_CIENTIFICO","NO_CIENTIFICO","NM_CIENTIFICO","DS_NOME_CIENTIFICO"),1000),
         "common_name":safe(get(row,"NOME_POPULAR"),100),
         "quantity":number(get(row,"QUANTIDADE")),
         "unit":safe(get(row,"UNIDADE_MEDIDA"),40),
         "group":safe(get(row,"GRUPO","DS_GRUPO","NM_GRUPO","NO_GRUPO"),120),
         "cites":safe(get(row,"CITES"),40),
         "source_item_id":safe(get(row,"SEQ_ESPECIME"),60),
         "taxonomy_id":safe(get(row,"SEQ_TAXONOMIA"),60),
         "infraction_type":safe(get(row,"TIPO"),100),
         "source_status":safe(get(row,"SITUACAO"),100),
         "source":"IBAMA auto de infração – espécime"}
   if item["scientific_name"] or item["common_name"] or item["quantity"] is not None:
    item_add(entries,item);counters["species_mentions"]+=1
  loaded["species_in_auto"]="ok"
 except Exception as exc:
  loaded["species_in_auto"]="unavailable: "+safe(exc,180); print("WARN auto species:",str(exc),file=sys.stderr)
 finally:
  if "path" in locals() and os.path.exists(path):os.unlink(path)
 
 # 3. Seizure terms linked by SEQ_AUTO_INFRACAO (not coordinates/date).
 try:
  path=download(URLS["seizure_terms"],"seizure terms")
  for row in rows(path):
   auto=get(row,"SEQ_AUTO_INFRACAO")
   f=byseq.get(auto)
   link_method="SEQ_AUTO_INFRACAO"
   if not f and not auto:
    number_series=(get(row,"CD_AUTO_INFRACAO")+" "+get(row,"SER_AUTO_INFRACAO")).strip().upper()
    candidates=by_notice.get(number_series,[]) if number_series and get(row,"SER_AUTO_INFRACAO") else []
    if len(candidates)==1:f=candidates[0];link_method="unique_official_auto_number_and_series";counters["terms_linked_by_unique_number_series"]+=1
   if not f:continue
   term=get(row,"SEQ_TAD")
   if not term:continue
   status_cancel=normalize(get(row,"ST_CANCELADO"))
   status_text=normalize(get(row,"DS_SIT_APREENSAO"))
   if status_cancel in {"SIM","S","TRUE","1"} or "CANCEL" in status_text:continue
   termitem={"id":safe(term,45),"number":safe(get(row,"CD_TAD"),50),
             "series":safe(get(row,"CD_SERIE_TAD"),15),
             "date":safe(get(row,"DT_APREENSAO"),30),
             "seizure_detail":public_narrative(get(row,"DS_TAD"),12000),
             "source":SEIZURES,"link_method":link_method}
   if termitem["seizure_detail"]:
    counters["terms_with_ds_tad"]+=1
   p=f["properties"]; arr=p.setdefault("seizure_terms",[])
   if not any(x["id"]==termitem["id"] for x in arr):arr.append(termitem)
   if not any(x is p for x in terms_by_seq[term]):terms_by_seq[term].append(p)
   counters["linked_seizure_terms"]+=1
  loaded["seizure_terms"]="ok"
 except Exception as exc:
  loaded["seizure_terms"]="unavailable: "+safe(exc,180);print("WARN seizure terms:",str(exc),file=sys.stderr)
 finally:
  if "path" in locals() and os.path.exists(path):os.unlink(path)
 
 # 4. Actual seized specimens identified by official SEQ_TAD foreign key.
 # Zip contains distinct source years; preserve all terms tied to our 2025 autos.
 if terms_by_seq:
  try:
   path=download(URLS["seized_specimens"],"seized specimens")
   for row in rows(path):
    key=get(row,"SEQ_TAD")
    if key not in terms_by_seq:continue
    item={
      "scientific_name":safe(get(row,"NOME_CIENTIFICO","NO_CIENTIFICO","NM_CIENTIFICO","DS_NOME_CIENTIFICO"),1000),
      "common_name":safe(get(row,"NOME_POPULAR","NO_POPULAR"),110),
      "quantity":number(get(row,"QUANTIDADE","QT_ESPECIME","QT_ESPECIME_APREENDIDO")),
      "unit":safe(get(row,"UNIDADE_MEDIDA","DS_UNIDADE_MEDIDA"),45),
      "group":safe(get(row,"GRUPO","DS_GRUPO","NM_GRUPO","NO_GRUPO"),120),
      "term_id":safe(key,45),
      "source_item_id":safe(get(row,"ID_ESPECIME"),60),
      "taxonomy_id":safe(get(row,"ID_TAXONOMIA"),60),
      "infraction_type":safe(get(row,"TP_INFRACAO"),100),
      "source":"IBAMA termo de apreensão – espécime"}
    if not (item["scientific_name"] or item["common_name"] or item["quantity"] is not None):continue
    for props in terms_by_seq[key]:
     item_add(props.setdefault("seized_specimens",[]),item)
     counters["seized_specimens_linked"]+=1
   loaded["seized_specimens"]="ok"
  except Exception as exc:
   loaded["seized_specimens"]="unavailable: "+safe(exc,180);print("WARN seized specimens:",str(exc),file=sys.stderr)
  finally:
   if "path" in locals() and os.path.exists(path):os.unlink(path)
 
 # 5. Seized non-biological property (machines, timber, materials).
 if terms_by_seq:
  try:
   path=download(URLS["seized_goods"],"seized goods")
   for row in rows(path):
    key=get(row,"SEQ_TAD")
    if key not in terms_by_seq:continue
    item={"name":safe(get(row,"DS_BEM_APREENDIDO","DS_TIPO_BEM"),140),
          "kind":safe(get(row,"DS_TIPO_BEM"),100),
          "quantity":number(get(row,"QT_BEM_APREENDIDO")),
          "unit":safe(get(row,"DS_UNIDADE_MEDIDA"),45),
          "category":safe(get(row,"DS_CATEGORIA"),90),
          "term_id":safe(key,45),
          "source":"IBAMA termo de apreensão – bem"}
    if not (item["name"] or item["quantity"] is not None):continue
    for props in terms_by_seq[key]:
     item_add(props.setdefault("seized_goods",[]),item)
     counters["seized_goods_linked"]+=1
   loaded["seized_goods"]="ok"
  except Exception as exc:
   loaded["seized_goods"]="unavailable: "+safe(exc,180);print("WARN seized goods:",str(exc),file=sys.stderr)
  finally:
   if "path" in locals() and os.path.exists(path):os.unlink(path)
 
 for f in features:
  p=f["properties"]
  p.setdefault("categories",[p.get("category","other")])
  for x in ("species_referenced","seized_specimens","seized_goods","seizure_terms"):
   p.setdefault(x,[])
  if p.get("official",{}).get("narrative_detail"):counters["autos_with_des_auto_infracao"]+=1
  if any(t.get("seizure_detail") for t in p.get("seizure_terms",[])):counters["autos_with_ds_tad"]+=1
  for cat in p["categories"]:counters["category_"+cat]+=1
  for extra in ("species_referenced","seized_specimens","seized_goods","seizure_terms"):
   if p[extra]:counters["autos_with_"+extra]+=1
 for year in YEARS:
  data=datasets[year]
  year_features=data["features"]
  data["classification_version"]="ibama-fauna-brasil-2020-2025-v1"
  data["classification_methodology"]="Official classification + recorded administrative narrative; evidence-grounded multi-category tags; administrative records do not imply conviction."
  data["enrichment_sources"]=URLS
  data["enrichment_status"]=loaded
  data["generated_at"]=datetime.datetime.now(datetime.timezone.utc).isoformat()
  annual=collections.Counter()
  for item in year_features:
   props=item["properties"]
   for key in ("species_referenced","seized_specimens","seized_goods","seizure_terms"):
    if props.get(key):annual["autos_with_"+key]+=1
   for category in props["categories"]:annual["category_"+category]+=1
   if props.get("official",{}).get("narrative_detail"):annual["autos_with_des_auto_infracao"]+=1
   if any(term.get("seizure_detail") for term in props.get("seizure_terms",[])):annual["autos_with_ds_tad"]+=1
  data["stats"]={**data.get("stats",{}),**dict(annual)}
  base=os.path.join(DATA_DIR,"ibama-"+str(year)+".json")
  with open(base+".tmp","w",encoding="utf-8") as output:
   json.dump(data,output,ensure_ascii=False,separators=(",",":"))
  os.replace(base+".tmp",base)
  audit=os.path.join(DATA_DIR,"ibama-"+str(year)+"-audit.json")
  with open(audit,"w",encoding="utf-8") as output:
   json.dump({"generated_at":data["generated_at"],"year":year,
      "total_records":len(year_features),"counters":dict(annual),"resources":loaded,
      "notes":"Official identifier links only; administrative data; no approximate record joins"},
      output,ensure_ascii=False,indent=2)
  print("IBAMA ENRICHED",year,len(year_features),"records",json.dumps(dict(annual),ensure_ascii=False),flush=True)
 print("IBAMA MULTIYEAR RESOURCES",json.dumps(loaded,ensure_ascii=False),flush=True)
 print("IBAMA ENRICHMENT COUNTERS",json.dumps(dict(counters),ensure_ascii=False),flush=True)

if __name__=="__main__":main()

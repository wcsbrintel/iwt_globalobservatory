#!/usr/bin/env python3
"""Evidence-grounded IBAMA 2020–2025 enrichment, only official identifiers.

Inputs are six annual GeoJSON files generated by build-ibama-years.py.
Administrative details, species mentioned in an auto, and actual seized items
are kept DISTINCT. No offender fields or vehicle IDs
are exported. No record matching by municipality, coordinates or approximate date.
"""
